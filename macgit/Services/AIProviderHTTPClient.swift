import Foundation

nonisolated protocol AIProviderHTTPClient: Sendable {
    func data(for request: URLRequest) async throws -> (Data, HTTPURLResponse)
}

struct URLSessionAIProviderHTTPClient: AIProviderHTTPClient {
    func data(for request: URLRequest) async throws -> (Data, HTTPURLResponse) {
        let (data, response) = try await URLSession.shared.data(for: request)
        guard let response = response as? HTTPURLResponse else {
            throw CommitMessageGenerationError.providerRequestFailed(
                "The AI provider returned an invalid HTTP response."
            )
        }
        return (data, response)
    }
}
